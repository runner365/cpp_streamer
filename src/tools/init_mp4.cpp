int main(int argn, char** argv) {
    Logger* logger = new Logger("init_mp4.log");
    logger->SetLevel(LOGGER_INFO_LEVEL);
    logger->EnableConsole();
    if (argn < 2) {
        LogError(logger, "usage: init_mp4 <mp4 file>");
        return -1;
    }
    HEVC_DEC_CONF_RECORD hevc_dec_info;
    int ret = GetHevcDecInfoFromExtradata(&hevc_dec_info, video_data.data(), video_data.size());
    if (ret < 0) {
        LogError(logger, "GetHevcDecInfoFromExtradata failed");
        return -1;
    }
    std::string hevc_dec_info_dump = HevcDecInfoDump(&hevc_dec_info);
    LogInfof(logger, "hevc dec info:\n%s", hevc_dec_info_dump.c_str());

    int width = 0;
    int height = 0;
    for (const auto& nalu : hevc_dec_info.nalu_vec) {
        LogInfof(logger, "nalu type: %d, size: %zu", nalu.nal_unit_type, nalu.nal_data_vec[0].nalu_data.size());
        if (nalu.nal_unit_type == NAL_UNIT_SPS) {
            LogInfoData(logger,
                (uint8_t*)nalu.nal_data_vec[0].nalu_data.data(),
                nalu.nal_data_vec[0].nalu_data.size(),
                "HEVC SPS data");
            if (ParseHevcSpsFinal(nalu.nal_data_vec[0].nalu_data.data(), nalu.nal_data_vec[0].nalu_data.size(), &width, &height, logger) == 0) {
                LogInfof(logger, "HEVC SPS: width=%d, height=%d", width, height);
            } else {
                LogError(logger, "ParseHevcSps failed");
            }
        }
    }
    char* mp4_file = argv[1];
    FtypBox* ftyp_box = new FtypBox();
    ftyp_box->major_brand_ = MAKE_TAG('i', 's', 'o', '5');
    ftyp_box->minor_version_ = 512;

    ftyp_box->compatible_brands_[0] = MAKE_TAG('i', 's', 'o', '5');
    ftyp_box->compatible_brands_[1] = MAKE_TAG('i', 's', 'o', '6');
    ftyp_box->compatible_brands_[2] = MAKE_TAG('m', 'p', '4', '1');
    ftyp_box->brands_count_ = 3;

    size_t ftyp_len = 0;
    uint8_t* ftyp_data = ftyp_box->Serialize(ftyp_len);
    LogInfof(logger, "ftyp box: %s", ftyp_box->Dump().c_str());
    LogInfof(logger, "ftyp box len: %zu", ftyp_len);

    MoovBox* moov_box = new MoovBox();
    size_t moov_len = 0;
    uint8_t* moov_data = nullptr;

    if (moov_box) {
        moov_box->mvhd_ = new MvhdBox();
        moov_box->mvhd_->version_flag_ = 0;
        moov_box->mvhd_->creation_time_ = 0;
        moov_box->mvhd_->modification_time_ = 0;
        moov_box->mvhd_->timescale_ = 1000;
        moov_box->mvhd_->duration_ = 0;
        moov_box->mvhd_->rate_ = 65536;
        moov_box->mvhd_->volume_ = 0x0100;
        moov_box->mvhd_->next_track_id_ = 2;

        TrakBox* video_trak = new TrakBox();
        if (video_trak) {
            video_trak->tkhd_ = new TkhdBox();
            video_trak->tkhd_->version_flag_ = MAKE_TAG(0, 0, 0, 3);
            video_trak->tkhd_->creation_time_ = 0;
            video_trak->tkhd_->modification_time_ = 0;
            video_trak->tkhd_->track_id_ = 1;
            video_trak->tkhd_->duration_ = 0;
            video_trak->tkhd_->width_ = ((uint32_t)width << 16);
            video_trak->tkhd_->height_ = ((uint32_t)height << 16);

            video_trak->edts_ = new EdtsBox();
            video_trak->edts_->elst_ = new ElstBox();

            video_trak->mdia_ = new MdiaBox();
            video_trak->mdia_->mdhd_ = new MdhdBox();
            video_trak->mdia_->mdhd_->timescale_ = 1000;

            video_trak->mdia_->hdlr_ = new HdlrBox();
            video_trak->mdia_->hdlr_->handler_type_ = MAKE_TAG('v', 'i', 'd', 'e');
            video_trak->mdia_->hdlr_->handler_descr_ = "VideoHandler";

            video_trak->mdia_->minf_ = new MinfBox();
            video_trak->mdia_->minf_->vmhd_ = new VmhdBox();
            video_trak->mdia_->minf_->dinf_ = new DinfBox();
            video_trak->mdia_->minf_->dinf_->dref_ = new DrefBox();
        
            UrlBox* url_box = new UrlBox();
            url_box->version_flag_ = 0;
            url_box->location_ = "http://example.com/video";
            video_trak->mdia_->minf_->dinf_->dref_->urls_box_.push_back(url_box);

            video_trak->mdia_->minf_->stbl_ = new StblBox();
            video_trak->mdia_->minf_->stbl_->stsd_ = new StsdBox();
            video_trak->mdia_->minf_->stbl_->stsd_->entry_count_ = 1;
            video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_ = new Hvc1Box();
            char* compressorname = video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->compressorname_;
            memset(compressorname, 0, 32);
            strncpy(compressorname, "Lavc62.11.100 libx265", 32);
            video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->width_ = width;
            video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->height_ = height;

            video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->hvcC_ = new HvcCBox();
            video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->hvcC_->hex_data_.resize(video_data.size());
            memcpy(video_trak->mdia_->minf_->stbl_->stsd_->hvc1_box_->hvcC_->hex_data_.data(),
                video_data.data(),
                video_data.size());

            video_trak->mdia_->minf_->stbl_->stts_ = new SttsBox();
            video_trak->mdia_->minf_->stbl_->stsc_ = new StscBox();
            video_trak->mdia_->minf_->stbl_->stsz_ = new StszBox();
            video_trak->mdia_->minf_->stbl_->stco_ = new StcoBox();

            moov_box->traks_.push_back(video_trak);
        }

        TrakBox* audio_trak = new TrakBox();
        if (audio_trak) {
            audio_trak->tkhd_ = new TkhdBox();
            audio_trak->tkhd_->version_flag_ = MAKE_TAG(0, 0, 0, 3);
            audio_trak->tkhd_->creation_time_ = 0;
            audio_trak->tkhd_->modification_time_ = 0;
            audio_trak->tkhd_->track_id_ = 2;
            audio_trak->tkhd_->duration_ = 0;
            audio_trak->tkhd_->width_ = 0;
            audio_trak->tkhd_->height_ = 0;

            audio_trak->edts_ = new EdtsBox();
            audio_trak->edts_->elst_ = new ElstBox();

            audio_trak->mdia_ = new MdiaBox();
            audio_trak->mdia_->mdhd_ = new MdhdBox();
            audio_trak->mdia_->mdhd_->timescale_ = 48000;

            audio_trak->mdia_->hdlr_ = new HdlrBox();
            audio_trak->mdia_->hdlr_->handler_type_ = MAKE_TAG('s', 'o', 'u', 'n');
            audio_trak->mdia_->hdlr_->handler_descr_ = "SoundHandler";

            audio_trak->mdia_->minf_ = new MinfBox();
            audio_trak->mdia_->minf_->smhd_ = new SmhdBox();
            audio_trak->mdia_->minf_->dinf_ = new DinfBox();
            audio_trak->mdia_->minf_->dinf_->dref_ = new DrefBox();
        
            UrlBox* url_box = new UrlBox();
            url_box->version_flag_ = 1;
            url_box->location_ = "http://example.com/audio";
            audio_trak->mdia_->minf_->dinf_->dref_->urls_box_.push_back(url_box);

            OpusExtraHandler opus_handler;
            int ret = opus_handler.DemuxExtraData(audio_data.data(), audio_data.size());
            LogInfof(logger, "opus extra data ret=%d, channel=%d, samplerate=%d, map_type=%d",
                ret,
                opus_handler.channel_,
                opus_handler.samperate_,
                opus_handler.map_type_);
            audio_trak->mdia_->minf_->stbl_ = new StblBox();
            audio_trak->mdia_->minf_->stbl_->stsd_ = new StsdBox();
            audio_trak->mdia_->minf_->stbl_->stsd_->entry_count_ = 1;
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_ = new OpusBox();
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->data_ref_index_ = 1;
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->version_ = 0;
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->channelcount_ = opus_handler.channel_;
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->samplerate_ = opus_handler.samperate_;
            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->samplesize_ = 16;//opus must be 16bits

            audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->extra_data_.resize(audio_data.size());
            memcpy(audio_trak->mdia_->minf_->stbl_->stsd_->opus_box_->extra_data_.data(),
                audio_data.data(),
                audio_data.size());
            
            audio_trak->mdia_->minf_->stbl_->stts_ = new SttsBox();
            audio_trak->mdia_->minf_->stbl_->stsc_ = new StscBox();
            audio_trak->mdia_->minf_->stbl_->stsz_ = new StszBox();
            audio_trak->mdia_->minf_->stbl_->stco_ = new StcoBox();
            moov_box->traks_.push_back(audio_trak);
        }
        
        moov_data = moov_box->Serialize(moov_len);
    }

    FILE* file_p = fopen(mp4_file, "wb+");
    if (!file_p) {
        LogError(logger, "failed to open mp4 file");
        delete ftyp_box;
        delete logger;
        return -1;
    }
    fwrite(ftyp_data, 1, ftyp_len, file_p);
    if (moov_data) {
        fwrite(moov_data, 1, moov_len, file_p);
    }
    
    fclose(file_p);

    delete ftyp_box;
    delete moov_box;
    delete[] ftyp_data;
    delete[] moov_data;
    delete logger;
    return 0;
}